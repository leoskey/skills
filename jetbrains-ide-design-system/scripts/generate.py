"""Generate both adapters from one token file. Offline, Python standard library only."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def kebab(value):
    return re.sub(r'([a-z])([A-Z])', r'\1-\2', value).lower()

def dart_color(value):
    raw = value.lstrip('#')
    return '0x' + ('FF' + raw if len(raw) == 6 else raw[6:8] + raw[:6])

def outputs(root=ROOT):
    t = json.loads((root / 'assets/tokens.json').read_text(encoding='utf-8'))
    def palette(mode):
        return '\n'.join(f'  --jb-{kebab(k)}: {v[mode]};' for k, v in t['colors'].items())
    css = '/* Generated by scripts/generate.py. Edit assets/tokens.json. */\n'
    css += ':root {\n' + '\n'.join(f'  --jb-{kebab(k)}: {v["value"]}px;' for k, v in t['metrics'].items())
    css += '\n' + '\n'.join(f'  --jb-{kebab(k)}: {t["typography"][k] / 16:g}rem;' for k in ['uiSize','smallSize','headingSize','codeSize']) + '\n}\n'
    css += ':root {\n' + '\n'.join(f'  --jb-{kebab(k)}: {json.dumps(t["typography"][k])};' for k in ['uiFamily','codeFamily']) + '\n}\n'
    css += ':root, [data-jb-theme="light"] {\n  color-scheme: light;\n' + palette('light') + '\n}\n'
    css += '[data-jb-theme="dark"] {\n  color-scheme: dark;\n' + palette('dark') + '\n}\n'
    css += '@media (prefers-color-scheme: dark) {\n  :root:not([data-jb-theme]) {\n    color-scheme: dark;\n' + palette('dark') + '\n  }\n}\n'
    css += '[data-jb-density="compact"] {\n  --jb-control-height: var(--jb-control-height-compact);\n  --jb-tree-row: var(--jb-tree-row-compact);\n  --jb-island-radius: var(--jb-island-radius-compact);\n  --jb-island-gap: var(--jb-island-gap-compact);\n}\n'
    dart = "// Generated by scripts/generate.py. Edit assets/tokens.json.\nimport 'package:flutter/material.dart';\n\n"
    dart += 'class JbColors extends ThemeExtension<JbColors> {\n  const JbColors(this.values);\n  final Map<String, Color> values;\n  Color operator [](String key) => values[key]!;\n'
    for mode in ['light', 'dark']:
        dart += f'  static const {mode} = JbColors({{\n' + '\n'.join(f"    '{k}': Color({dart_color(v[mode])})," for k, v in t['colors'].items()) + '\n  });\n'
    dart += '''  @override
  JbColors copyWith({Map<String, Color>? values}) => JbColors({...this.values, ...?values});
  @override
  JbColors lerp(covariant JbColors? other, double t) {
    if (other == null) return this;
    return JbColors({for (final key in values.keys) key: Color.lerp(values[key], other.values[key], t)!});
  }
}

abstract final class JbMetrics {
'''
    dart += '\n'.join(f'  static const double {k} = {float(v["value"])};' for k, v in t['metrics'].items()) + '\n}\n'
    dart += '\nabstract final class JbType {\n' + '\n'.join(f'  static const double {k} = {float(t["typography"][k])};' for k in ['uiSize','smallSize','headingSize','codeSize'])
    dart += '\n' + '\n'.join(f'  static const String {k} = {json.dumps(t["typography"][k])};' for k in ['uiFamily','codeFamily']) + '\n}\n'
    return {'assets/web/jb-tokens.css': css, 'assets/flutter/lib/jb_tokens.g.dart': dart}

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true', help='Verify committed adapters without writing')
    args = p.parse_args()
    stale = []
    for name, text in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8', newline='\n')
    if stale:
        raise SystemExit('Stale generated adapters: ' + ', '.join(stale))
    print('Adapters verified.' if args.check else 'Generated CSS and Dart adapters.')

if __name__ == '__main__':
    main()
